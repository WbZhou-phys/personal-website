const header = document.querySelector(".site-header");
const navToggle = document.querySelector(".nav-toggle");
const navLinks = document.querySelectorAll(".primary-nav a");
const languageButtons = document.querySelectorAll(".language-button");
const metaDescription = document.querySelector('meta[name="description"]');

function getLanguageFromUrl() {
  const language = new URLSearchParams(window.location.search).get("lang");
  return language === "zh" ? "zh" : "en";
}

function setNavigationState(isOpen) {
  header.classList.toggle("nav-open", isOpen);
  navToggle.setAttribute("aria-expanded", String(isOpen));
  const key = isOpen ? "a11y.menuClose" : "a11y.menuOpen";
  navToggle.setAttribute("aria-label", translations[document.documentElement.lang === "zh-CN" ? "zh" : "en"][key]);
}

function applyLanguage(language, updateUrl = true) {
  const isChinese = language === "zh";
  const copy = translations[language];

  document.documentElement.lang = isChinese ? "zh-CN" : "en";
  document.title = pageMeta[language].title;
  metaDescription?.setAttribute("content", pageMeta[language].description);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = copy[element.dataset.i18n];
    if (value) element.textContent = value;
  });

  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const value = copy[element.dataset.i18nHtml];
    if (value) element.innerHTML = value;
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const value = copy[element.dataset.i18nAriaLabel];
    if (value) element.setAttribute("aria-label", value);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = copy[element.dataset.i18nAlt];
    if (value) element.setAttribute("alt", value);
  });

  document.querySelectorAll("[data-i18n-title]").forEach((element) => {
    const value = copy[element.dataset.i18nTitle];
    if (value) element.setAttribute("title", value);
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.language === language;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  if (updateUrl) {
    const url = new URL(window.location.href);
    if (isChinese) {
      url.searchParams.set("lang", "zh");
    } else {
      url.searchParams.delete("lang");
    }
    window.history.replaceState({}, "", `${url.pathname}${url.search}${url.hash}`);
  }

  setNavigationState(false);
}

window.addEventListener("scroll", () => {
  header.classList.toggle("is-scrolled", window.scrollY > 24);
}, { passive: true });

navToggle.addEventListener("click", () => {
  setNavigationState(!header.classList.contains("nav-open"));
});

navLinks.forEach((link) => {
  link.addEventListener("click", () => setNavigationState(false));
});

languageButtons.forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.language));
});

window.addEventListener("popstate", () => applyLanguage(getLanguageFromUrl(), false));

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") setNavigationState(false);
});

document.getElementById("year").textContent = new Date().getFullYear();
applyLanguage(getLanguageFromUrl(), false);
